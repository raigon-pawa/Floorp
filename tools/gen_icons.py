"""Generate the Archwave mark (wave lines inside a globe ring) as Android vector drawables.

Same geometry as the "small" desktop icon (static/gecko/archwave-icon/gen.py in the desktop
repository): a 512 unit square, globe centred at 256,256, ring radius 168 and 24 wide, five waves.
The desktop SVG clips the waves with a circle; here each wave is simply cut where it meets the
ring, which hides the ends, so the drawables need no clip path.

Usage: tools/gen_icons.py           write the drawables
       tools/gen_icons.py --check   exit 1 if the committed drawables differ from the output

  drawable/ic_icon_foreground.xml  adaptive icon foreground, 108dp; the mark is 60dp wide, inside
                                   the 66dp safe zone
  drawable/ic_icon_monochrome.xml  adaptive icon monochrome layer (themed icons), 108dp; the mark
                                   is 44dp wide like other themed glyphs, opaque strokes
  drawable/ic_notification.xml     status bar icon, 24dp, opaque strokes (only alpha is used),
                                   waves 1.5 times as thick so they survive at 18dp
"""

import math
import pathlib
import sys

RES = pathlib.Path(__file__).resolve().parent.parent / "app/src/main/res"
CX = CY = 256
RING_R, RING_W = 168, 24
CUT_R = RING_R - 6  # where the desktop icon clips the waves; under the ring
WAVES = 5
STEP = 7  # distance between wave points; small enough to look smooth at icon sizes

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- This Source Code Form is subject to the terms of the Mozilla Public
   - License, v. 2.0. If a copy of the MPL was not distributed with this
   - file, You can obtain one at http://mozilla.org/MPL/2.0/. -->
<!-- Generated by tools/gen_icons.py. Do not edit by hand. -->
"""


def wave_y(x, y0, amp, phase, drift):
    t = (x - 40) / 432
    k = 1.15 * t * 2 * math.pi
    return y0 + amp * math.sin(k + phase) + amp * 0.45 * math.sin(2.3 * k + phase * 1.7) + drift * math.sin(t * math.pi)


def waves():
    """Yield (path data, stroke width, opacity) for each wave, cut at the globe."""
    for i in range(WAVES):
        y0 = CY - RING_R + 18 + i * (2 * RING_R - 36) / (WAVES - 1)
        mid = 1 - abs(i - (WAVES - 1) / 2) / ((WAVES - 1) / 2)
        args = (y0, 6 + 16 * mid, i * 0.55, -10 * mid)
        inside = [x for x in range(40, 473) if math.hypot(x - CX, wave_y(x, *args) - CY) <= CUT_R]
        first, last = inside[0], inside[-1]
        count = math.ceil((last - first) / STEP)
        xs = [first + (last - first) * n / count for n in range(count + 1)]
        points = " L".join(f"{x:.1f},{wave_y(x, *args):.1f}" for x in xs)
        yield "M" + points, 14 if i == WAVES // 2 else 11, max(0.35 + 0.6 * mid, 0.75)


def drawable(size_dp, viewport, opaque, wave_scale=1):
    """The mark centred in a square viewport of `viewport` icon units, drawn at `size_dp`."""
    shift = (viewport - 512) / 2
    ring = f"M{CX - RING_R},{CY}a{RING_R},{RING_R} 0 1,0 {2 * RING_R},0a{RING_R},{RING_R} 0 1,0 -{2 * RING_R},0"
    paths = [(ring, RING_W, 1.0)] + [(d, w * wave_scale, o) for d, w, o in waves()]
    out = [
        HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{size_dp}dp"',
        f'    android:height="{size_dp}dp"',
        f'    android:viewportWidth="{viewport}"',
        f'    android:viewportHeight="{viewport}">',
        f'    <group android:translateX="{shift:g}" android:translateY="{shift:g}">',
    ]
    for data, width, opacity in paths:
        out += [
            "        <path",
            '            android:strokeColor="#FFFFFFFF"',
            f'            android:strokeWidth="{width:g}"',
            '            android:strokeLineCap="round"',
            '            android:strokeLineJoin="round"',
        ]
        if opacity < 1 and not opaque:
            out.append(f'            android:strokeAlpha="{opacity:.2f}"')
        out.append(f'            android:pathData="{data}" />')
    out += ["    </group>", "</vector>", ""]
    return "\n".join(out)


FILES = {
    # 648 = 108dp * 6: the ring's outer edge (radius 180) lands at 30dp, inside the 33dp safe zone.
    "drawable/ic_icon_foreground.xml": drawable(108, 648, opaque=False),
    # 884 = 360 * 108 / 44: a themed icon's glyph is about 44dp wide; at 60dp the ring hugs the tile edge.
    "drawable/ic_icon_monochrome.xml": drawable(108, 884, opaque=True),
    # 376 leaves 8 units (half a dp) around the ring.
    "drawable/ic_notification.xml": drawable(24, 376, opaque=True, wave_scale=1.5),
}

if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        stale = [name for name, text in FILES.items() if (RES / name).read_text() != text]
        if stale:
            sys.exit("out of date, run tools/gen_icons.py: " + ", ".join(stale))
    else:
        for name, text in FILES.items():
            (RES / name).write_text(text)
            print("wrote", RES / name)
